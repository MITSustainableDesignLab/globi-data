"""Generated Markdown and index files.

These pages are the entire interface for anyone who is not going to install a
CLI: a partner page that lists versions and links to downloads, a version page
that says what the files are and what changed, and a status page showing which
results are out of date. They are regenerated by ``globi-data index --write``
and checked in CI, so they can never drift from the manifests.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any

from .models import InputVersionManifest, VersionsLedger

if TYPE_CHECKING:
    from .roles import BundlePlan
    from .status import StatusRow

# Plain-language descriptions of each role, shown in version READMEs so someone
# unfamiliar with the pipeline can tell what a file is for.
ROLE_DESCRIPTIONS: dict[str, str] = {
    "experiment_manifest": "Top-level description of the experiment (name, scenario).",
    "file_config": "Points at the other input files.",
    "gis_preprocessor_config": "Rules for cleaning the building geometry.",
    "overheating_config": "Temperature thresholds for the overheating analysis.",
    "hourly_data_config": "Which hourly variables to record.",
    "db_file": "Component and material library (SQLite).",
    "semantic_fields_file": "Declares the building attributes and their allowed values.",
    "component_map_file": "Maps building attributes to envelope, HVAC and DHW components.",
    "epwzip_file": "Current-climate weather file (remote URL).",
    "epwzip_file_local": "Current-climate weather file (stored here).",
    "ftmy_zip": "Future-climate (2050 morphed) weather file.",
    "gis_file": "Building footprints. Stored in globi-partners-data, not here.",
    "weather_lookup": "Maps each area to its weather station.",
    "context": "Pre-processed building context table.",
}


# What each weather file extension actually is, so the table has no blank rows.
_WEATHER_KINDS: dict[str, str] = {
    ".epw": "hourly weather data",
    ".ddy": "design-day conditions",
    ".zip": "packaged weather files",
    ".stat": "weather summary statistics",
}


def _describe(path: str, role: str) -> str:
    """Explain a file in plain language, by role or by where it sits."""
    if role and role in ROLE_DESCRIPTIONS:
        return ROLE_DESCRIPTIONS[role]

    parts = path.split("/")
    suffix = "." + path.rsplit(".", 1)[-1] if "." in parts[-1] else ""
    kind = _WEATHER_KINDS.get(suffix.lower(), "")
    if "weather_ftmy" in parts:
        return (
            f"Future climate (2050) — {kind}."
            if kind
            else "Future-climate weather file."
        )
    if "weather" in parts:
        return f"Current climate — {kind}." if kind else "Current-climate weather file."
    if "runs" in parts:
        return "Record of how a previous batch of runs was allocated."
    return ""


def _bytes(size: int | None) -> str:
    """Format a byte count for humans."""
    if size is None:
        return "-"
    for unit, limit in (("GB", 1e9), ("MB", 1e6), ("KB", 1e3)):
        if size >= limit:
            return f"{size / limit:.1f} {unit}"
    return f"{size} B"


def _table(headers: list[str], rows: list[list[str]]) -> str:
    """Render a GitHub-flavoured Markdown table."""
    if not rows:
        return "_None._\n"
    out = ["| " + " | ".join(headers) + " |"]
    out.append("|" + "|".join("---" for _ in headers) + "|")
    for row in rows:
        out.append("| " + " | ".join(row) + " |")
    return "\n".join(out) + "\n"


def input_version_readme(
    manifest: InputVersionManifest, plan: BundlePlan | None = None
) -> str:
    """Render the README that sits inside a frozen input version directory."""
    m = manifest
    lines: list[str] = [
        f"# {m.partner} — input {m.version}",
        "",
        m.summary.strip(),
        "",
        f"- **Created:** {m.created_at}",
        f"- **Impact:** `{m.impact}`"
        + (
            "  (changes here can change simulation results)"
            if m.impact == "simulation-affecting"
            else "  (documentation only; results stay valid)"
        ),
    ]
    if m.parent_version:
        lines.append(
            f"- **Previous version:** [`{m.parent_version}`](../{m.parent_version}/)"
        )
    if m.source.commit:
        short = m.source.commit[:8]
        lines.append(
            f"- **Assembled from:** `{m.source.repo}` @ `{short}` (`{m.source.path}`)"
        )
    lines += [
        "",
        "> This folder is frozen. To change anything, create a new version — do not edit",
        "> these files in place.",
        "",
        "## Files",
        "",
    ]

    role_by_path: dict[str, str] = {}
    for role, value in m.globi.roles.items():
        if value and not value.startswith(("http", "s3://", "external:")):
            role_by_path.setdefault(value, role)

    rows = []
    for entry in m.files:
        if entry.path == "README.md":
            continue
        role = entry.role or role_by_path.get(entry.path, "")
        rows.append([
            f"`{entry.path}`",
            _bytes(entry.size_bytes),
            _describe(entry.path, role),
        ])
    lines.append(_table(["File", "Size", "What it is"], rows))

    if m.external_files:
        lines += [
            "## Not stored here",
            "",
            "These files are too large for this repository. Their fingerprints are recorded",
            "so results stay traceable, but the bytes live elsewhere.",
            "",
        ]
        rows = [
            [
                f"`{e.path}`",
                _bytes(e.size_bytes),
                f"`{e.stored_in.repo}` / `{e.stored_in.path}`",
                e.reason,
            ]
            for e in m.external_files
        ]
        lines.append(_table(["File", "Size", "Where it lives", "Why"], rows))

    if m.changes:
        lines += ["## What changed", ""]
        rows = [[f"`{c.path}`", c.change, c.note or ""] for c in m.changes]
        lines.append(_table(["File", "Change", "Note"], rows))

    if m.not_carried_over:
        lines += [
            "## Not carried over from the source repo",
            "",
            "Present in the source directory but deliberately excluded, so nothing was",
            "dropped silently:",
            "",
        ]
        lines += [f"- `{item}`" for item in m.not_carried_over]
        lines.append("")

    if plan and plan.warnings:
        lines += ["## Warnings", ""] + [f"- {w}" for w in plan.warnings] + [""]

    lines += [
        "## Fingerprint",
        "",
        f"- `bundle_sha256`: `{m.bundle_sha256}`",
        "",
        "Verify this folder yourself with `globi-data inputs verify "
        f"{m.partner} --version {m.version}`.",
        "",
    ]
    return "\n".join(lines)


def partner_readme(
    partner: str, ledger: VersionsLedger, current: InputVersionManifest
) -> str:
    """Render the partner landing page listing every version."""
    lines = [
        f"# {partner} — inputs",
        "",
        f"**Current version: [`{current.version}`]({current.version}/)**",
        "",
        "Each folder below is one complete, self-contained set of input files. Older",
        "versions are kept exactly as they were, so results produced from them stay",
        "reproducible.",
        "",
        "## How to download",
        "",
        f"Open [`{current.version}/`]({current.version}/) and use the download button on any",
        "file, or grab the whole folder as a zip from the",
        f"[{partner}-{current.version} release](../../../releases/tag/{partner}-{current.version}).",
        "",
        "## Versions",
        "",
    ]
    rows = []
    for entry in reversed(ledger.versions):
        badge = {
            "active": "**current**",
            "superseded": "superseded",
            "retracted": "⚠️ retracted",
        }.get(entry.status, entry.status)
        summary = entry.summary.strip().splitlines()[0] if entry.summary.strip() else ""
        if entry.retracted_reason:
            summary = f"{summary} — retracted: {entry.retracted_reason}"
        rows.append([
            f"[`{entry.version}`]({entry.version}/)",
            badge,
            entry.created_at[:10],
            f"`{entry.impact}`" if entry.impact else "",
            summary,
        ])
    lines.append(_table(["Version", "Status", "Date", "Impact", "What changed"], rows))
    lines += [
        "## Adding a new version",
        "",
        "Never edit a version folder in place. See",
        "[docs/HOW-TO-ADD-A-VERSION.md](../../../docs/HOW-TO-ADD-A-VERSION.md) — there is a",
        "browser-based route that needs no software installed.",
        "",
    ]
    return "\n".join(lines)


def inputs_index_readme(rows: list[dict[str, Any]]) -> str:
    """Render the top-level inputs landing page."""
    lines = [
        "# Inputs",
        "",
        "One folder per partner. Each contains numbered versions (`v001`, `v002`, …);",
        "the current one is named in that partner's `CURRENT.yml` and at the top of its",
        "README.",
        "",
    ]
    table = [
        [
            f"[{row['partner']}](partners/{row['partner']}/)",
            f"`{row['current']}`",
            str(row["versions"]),
            row["updated"][:10],
            _bytes(row["bytes"]),
            row.get("kind", ""),
        ]
        for row in rows
    ]
    lines.append(
        _table(["Partner", "Current", "Versions", "Updated", "Size", "Kind"], table)
    )
    lines += [
        "> Building footprint files (`buildings.geojson`) are not stored here — they are",
        "> too large. Each version records their exact fingerprint and where to find them.",
        "",
    ]
    return "\n".join(lines)


def outputs_index_readme(rows: list[dict[str, Any]]) -> str:
    """Render the top-level outputs landing page."""
    lines = [
        "# Outputs",
        "",
        "One folder per simulation run, named the way the run is named:",
        "`<Partner>/<weather>/<Scenario>`. Each holds numbered versions recording where",
        "the result files live in S3 and exactly which inputs and code produced them.",
        "",
        "The result files themselves are not stored in git — there are about 11 GB of them.",
        "Download them with `globi-data outputs download <experiment>`.",
        "",
        "See [STATUS.md](STATUS.md) for which results are up to date.",
        "",
    ]
    table = [
        [
            f"[{row['experiment']}](runs/{row['experiment']}/)",
            f"`{row['current']}`",
            row.get("scythe_version", ""),
            row.get("run_timestamp", "")[:10],
            str(row.get("result_count", "")),
            f"`{row.get('input_version', '')}`",
        ]
        for row in rows
    ]
    lines.append(
        _table(
            ["Experiment", "Version", "Run", "Date", "Results", "Built from input"],
            table,
        )
    )
    return "\n".join(lines)


STATE_BADGES: dict[str, str] = {
    "ok": "🟢 up to date",
    "stale": "🔴 stale",
    "metadata-drift": "🔵 docs changed only",
    "code-drift": "🟡 code changed",
    "inferred": "⚪ assumed",
    "unpinned": "⚪ unknown",
    "broken-pin": "🔴 broken",
    "tampered": "🔴 tampered",
}


def status_markdown(rows: list[StatusRow], generated_at: str) -> str:
    """Render the staleness table published as ``outputs/STATUS.md``."""
    lines = [
        "# Results status",
        "",
        f"_Generated {generated_at}._",
        "",
        "Whether each set of results still matches the current inputs.",
        "",
        "| | Meaning |",
        "|---|---|",
        "| 🟢 up to date | Built from the current inputs. |",
        "| 🔴 stale | Inputs changed in a way that affects results. Re-run. |",
        "| 🔵 docs changed only | Inputs changed, but only documentation. No re-run needed. |",
        "| 🟡 code changed | Simulation code moved on since this run. |",
        "| ⚪ assumed | Which inputs produced this was inferred, not recorded. |",
        "| 🔴 broken / tampered | The recorded inputs cannot be found or no longer match. |",
        "",
    ]
    table = [
        [
            f"[{row.experiment}](runs/{row.experiment}/)",
            STATE_BADGES.get(row.state, row.state),
            f"`{row.pinned_version or '-'}`",
            f"`{row.current_version or '-'}`",
            row.detail,
        ]
        for row in rows
    ]
    lines.append(
        _table(["Experiment", "Status", "Built from", "Current input", "Detail"], table)
    )

    counts: dict[str, int] = {}
    for row in rows:
        counts[row.state] = counts.get(row.state, 0) + 1
    if counts:
        summary = ", ".join(
            f"{count} {STATE_BADGES.get(state, state)}"
            for state, count in sorted(counts.items())
        )
        lines += [f"**{len(rows)} experiments:** {summary}", ""]
    return "\n".join(lines)
